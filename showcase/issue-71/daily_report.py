#!/usr/bin/env python3
"""
daily_report.py — Automated Daily NIDS Markdown Digest
Queries Loki for the past 24 h of NIDS events, computes statistics,
and writes a markdown report. Run via cron at 23:59 each night.

Requirements:
    pip install requests jinja2

Usage:
    python3 daily_report.py --loki http://localhost:3100 --out /var/log/nids/

Cron entry:
    59 23 * * *  pi  python3 /opt/nids/daily_report.py >> /var/log/nids/cron.log 2>&1
"""

import argparse
import json
import logging
import os
from collections import Counter, defaultdict
from datetime import datetime, timezone, timedelta

import requests
from jinja2 import Template

log = logging.getLogger(__name__)
logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s")

REPORT_TEMPLATE = """# 🛡 NIDS Daily Digest — {{ date }}

## Summary

| Metric | Value |
|---|---|
| Total flows analysed | {{ total_flows }} |
| Threat events (high-severity) | {{ threat_count }} |
| Unique attacker IPs | {{ unique_attackers }} |
| Most-targeted port | {{ top_port }} |
| Peak hour (UTC) | {{ peak_hour }}:00 |

---

## Top 10 Attacker IPs

| Rank | IP Address | Events | Top Label |
|---|---|---|---|
{% for row in top_attackers -%}
| {{ loop.index }} | `{{ row.ip }}` | {{ row.count }} | `{{ row.label }}` |
{% endfor %}

---

## Attack Category Breakdown

| Category | Count | % |
|---|---|---|
{% for row in label_breakdown -%}
| `{{ row.label }}` | {{ row.count }} | {{ row.pct }}% |
{% endfor %}

---

## Most-Targeted Services

| Port | Proto | Hits |
|---|---|---|
{% for row in top_ports -%}
| {{ row.port }} | {{ row.proto }} | {{ row.count }} |
{% endfor %}

---

*Generated by daily_report.py · Pi 4 NIDS Station · {{ generated_at }}*
"""

def query_loki(loki_url: str, hours: int = 24) -> list[dict]:
    end   = datetime.now(timezone.utc)
    start = end - timedelta(hours=hours)
    params = {
        "query": '{job="nids", severity="high"}',
        "start": str(int(start.timestamp() * 1e9)),
        "end":   str(int(end.timestamp()   * 1e9)),
        "limit": 5000,
        "direction": "forward",
    }
    resp = requests.get(f"{loki_url}/loki/api/v1/query_range",
                        params=params, timeout=30)
    resp.raise_for_status()
    events = []
    for stream in resp.json().get("data", {}).get("result", []):
        for _ts, line in stream["values"]:
            try:
                events.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    return events

def build_report(events: list[dict], date_str: str) -> str:
    threat_events = [e for e in events if e.get("ml_label") not in ("benign","unknown","")]
    total_flows   = len(events)
    threat_count  = len(threat_events)

    attacker_labels: dict[str, Counter] = defaultdict(Counter)
    port_proto: Counter = Counter()
    hour_counter: Counter = Counter()

    for e in threat_events:
        ip    = e.get("src_ip", "?")
        label = e.get("ml_label", "unknown")
        port  = e.get("dst_port", 0)
        proto = e.get("proto", "?")
        ts    = e.get("ts", "")
        attacker_labels[ip][label] += 1
        port_proto[(port, proto)] += 1
        if ts:
            try:
                hour_counter[datetime.fromisoformat(ts.replace("Z","+00:00")).hour] += 1
            except Exception:
                pass

    top_attackers = []
    for ip, cntr in sorted(attacker_labels.items(),
                           key=lambda x: sum(x[1].values()), reverse=True)[:10]:
        count = sum(cntr.values())
        top_attackers.append({"ip": ip, "count": count, "label": cntr.most_common(1)[0][0]})

    all_labels: Counter = Counter()
    for cntr in attacker_labels.values():
        all_labels.update(cntr)
    label_total = max(sum(all_labels.values()), 1)
    label_breakdown = [
        {"label": lbl, "count": cnt, "pct": round(cnt*100/label_total,1)}
        for lbl, cnt in all_labels.most_common()
    ]

    top_ports = [
        {"port": p, "proto": pr, "count": c}
        for (p, pr), c in port_proto.most_common(10)
    ]

    unique_attackers = len(attacker_labels)
    top_port = f"{top_ports[0]['port']}/{top_ports[0]['proto']}" if top_ports else "—"
    peak_hour = max(hour_counter, key=hour_counter.get) if hour_counter else "—"

    tpl = Template(REPORT_TEMPLATE)
    return tpl.render(
        date=date_str,
        total_flows=total_flows,
        threat_count=threat_count,
        unique_attackers=unique_attackers,
        top_port=top_port,
        peak_hour=peak_hour,
        top_attackers=top_attackers,
        label_breakdown=label_breakdown,
        top_ports=top_ports,
        generated_at=datetime.now(timezone.utc).isoformat(),
    )

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--loki",  default="http://localhost:3100")
    parser.add_argument("--out",   default="/var/log/nids/")
    parser.add_argument("--hours", type=int, default=24)
    args = parser.parse_args()

    log.info("Fetching last %d h from Loki …", args.hours)
    events   = query_loki(args.loki, args.hours)
    date_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    report   = build_report(events, date_str)

    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, f"nids_report_{date_str}.md")
    with open(path, "w") as fh:
        fh.write(report)
    log.info("Report written: %s", path)
    print(report)

if __name__ == "__main__":
    main()
